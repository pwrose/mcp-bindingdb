"""Session log of tool calls and the Markdown transcript rendered from it (create_transcript).

Modelled on mcp-okn's create_chat_transcript: the caller supplies the prompts and answers, the server
supplies the tool calls it actually ran, verbatim, with their results.
"""

from __future__ import annotations

import json
from datetime import datetime, timezone
from typing import Any

#: Not logged: schema lookups, and the transcript tools themselves.
UNLOGGED_TOOLS = {"describe_tables", "create_transcript", "transcript_to_html", "reset_tool_log", "get_tool_log",
                  "draw_structure_grid"}  # figures are logged separately


class ToolLog:
    """Successful tool calls and figures (draw_structure_grid) of this server process, in order."""

    def __init__(self) -> None:
        self.entries: list[dict[str, Any]] = []
        self.figures: list[Any] = []  # figures.Figure; ids count on across resets so they stay unique
        self.next_figure_id = 1

    def record(self, tool: str, arguments: dict[str, Any], result: Any) -> None:
        self.entries.append({"timestamp": datetime.now(timezone.utc).isoformat(timespec="seconds"),
                             "tool": tool, "arguments": dict(arguments), "result": result})

    def reset(self) -> tuple[int, int]:
        """Clear the log; returns the numbers of calls and figures cleared."""
        n = len(self.entries), len(self.figures)
        self.entries.clear()
        self.figures.clear()
        return n

    def listing(self) -> list[dict[str, Any]]:
        """The calls without their results, numbered from 1 as create_transcript's `calls` expects."""
        return [{"index": i, "timestamp": e["timestamp"], "call": signature(e, 200)}
                for i, e in enumerate(self.entries, start=1)]

    def figure(self, figure_id: int) -> Any:
        return next((f for f in self.figures if f.id == figure_id), None)


def signature(call: dict[str, Any], max_chars: int | None = None) -> str:
    """A call as Python-like text, e.g. search_compounds(query='imatinib', limit=3)."""
    args = ", ".join(f"{a}={v!r}" for a, v in (call.get("arguments") or {}).items())
    text = f"{call['tool']}({args})"
    return text if max_chars is None or len(text) <= max_chars else text[:max_chars - 1] + "…"


def render_transcript(*, title: str, when: str, model: str, release: str, generated_by: str,
                      exchanges: list[dict[str, Any]], calls: list[dict[str, Any]], max_rows: int | None,
                      skills: list[str], mcp_servers: list[str], figures: list[Any] = (),
                      unplaced_figures: list[Any] = ()) -> str:
    """The transcript as Markdown: header, the conversation turns (each with the figures it lists by id),
    any other figures, then the given tool calls. Figures are links to figures/<file>."""
    by_id = {f.id: f for f in figures}
    body = ["## Conversation", ""]
    if not exchanges:
        body += ["_No prompts recorded._", ""]
    for exchange in exchanges:
        body += ["👤 **User**", "", (exchange.get("prompt") or "(no prompt)").strip(), "", "---", "",
                 "🧠 **Assistant**", ""]
        if answer := (exchange.get("answer") or "").strip():
            body += [answer, ""]
        for figure_id in exchange.get("figures") or []:
            body += _figure_link(by_id[figure_id])
    if unplaced_figures:
        body += ["## Figures", ""]
        for figure in unplaced_figures:
            body += _figure_link(figure)
    if calls:
        body += ["## BindingDB tool calls", ""]
        for k, call in enumerate(calls, start=1):
            body += _render_call(call, k, max_rows)

    n_figures = sum(len(e.get("figures") or []) for e in exchanges) + len(unplaced_figures)
    contents = [plural(len(exchanges), "exchange"), *([plural(n_figures, "figure")] if n_figures else []),
                *([plural(len(calls), "tool call")] if calls else [])]
    window = _active_window(calls)
    header = [
        f"# {title}",
        "",
        f"- **Date:** {when}",
        f"- **Model:** {model}",
        *([f"- **Skills:** {' · '.join(skills)}"] if skills else []),
        *([f"- **External MCP servers:** {' · '.join(mcp_servers)}"] if mcp_servers else []),
        f"- **BindingDB release:** {release}",
        f"- **Generated by:** {generated_by}",
        *([f"- **Active window:** {window}"] if window else []),
        f"- **Contents:** {' · '.join(contents)}",
        "",
    ]
    return "\n".join([*header, *body]).rstrip() + "\n"


def _figure_link(figure: Any) -> list[str]:
    alt = figure.title.replace("[", "\\[").replace("]", "\\]")
    return [f"![Figure {figure.id}: {alt}](figures/{figure.file})", ""]


def clean_entries(entries: list[str] | None) -> list[str]:
    """Strip blanks and duplicates from a caller-supplied list (skills, MCP servers), keeping its order."""
    return list(dict.fromkeys(text for e in entries or [] if (text := str(e).strip())))


def plural(count: int, noun: str) -> str:
    return f"{count} {noun}{'' if count == 1 else 's'}"


def _active_window(calls: list[dict[str, Any]]) -> str:
    """'<first>–<last> UTC (<elapsed>)' from the logged calls' timestamps, or '' without calls."""
    if not calls:
        return ""
    times = sorted(datetime.fromisoformat(c["timestamp"]) for c in calls)
    first, last = times[0], times[-1]
    h, rem = divmod(int((last - first).total_seconds()), 3600)
    m, s = divmod(rem, 60)
    elapsed = f"{h}h {m}m" if h else (f"{m}m {s}s" if m else f"{s}s")
    if first.date() == last.date():
        return f"{first:%Y-%m-%d %H:%M}–{last:%H:%M} UTC ({elapsed})"
    return f"{first:%Y-%m-%dT%H:%MZ} → {last:%Y-%m-%dT%H:%MZ} ({elapsed})"


def _render_call(call: dict[str, Any], k: int, max_rows: int | None) -> list[str]:
    """One call: its arguments verbatim (run_sql's SQL as a sql block), then its result."""
    tool = call["tool"]
    args = dict(call.get("arguments") or {})
    sql = args.pop("sql", None) if tool == "run_sql" else None
    lines = [f"#### Call {k} — `{tool}`", ""]
    context = [call.get("timestamp", ""), *(f"{a}={v!r}" for a, v in args.items() if sql is not None)]
    lines += [f"_{' · '.join(c for c in context if c)}_", ""]
    if sql is not None:
        lines += ["```sql", sql.strip(), "```", ""]
    else:
        lines += ["```python", signature(call), "```", ""]
    return lines + _render_result(call.get("result"), max_rows)


def _is_table(key: str, value: Any) -> bool:
    return isinstance(value, list) and (key == "rows" or bool(value) and all(isinstance(r, dict) for r in value))


def _render_result(result: Any, max_rows: int | None) -> list[str]:
    """Lists of rows as Markdown tables (capped at max_rows); everything else as one JSON block."""
    if not isinstance(result, dict):
        return ["```", str(result).strip(), "```", ""]
    tables = {k: v for k, v in result.items() if _is_table(k, v)}
    skip = {"row_count", "truncated"} if "rows" in tables else set()
    other = {k: _cap(v, max_rows) for k, v in result.items() if k not in tables and k not in skip}
    lines = _render_molecules(result)
    if other:
        lines += ["```json", json.dumps(other, indent=2, ensure_ascii=False, default=str), "```", ""]
    for key, rows in tables.items():
        shown = rows if max_rows is None else rows[:max_rows]
        count = plural(result.get("row_count", len(rows)) if key == "rows" else len(rows), "row")
        if key == "rows" and result.get("truncated"):
            count += ", truncated at the limit"
        if len(shown) < len(rows):
            count += f" — showing first {len(shown)}"
        lines += [f"_{count}_" if key == "rows" else f"**{key}**: {count}", "", *_rows_to_table(shown)]
    return lines


def _render_molecules(result: dict[str, Any]) -> list[str]:
    """A name/smiles table of the molecules a result is about, outside its tables: the search query
    (substructure/similarity), a structure looked up by name, a single compound (get_compound).
    The HTML transcript draws them, like every smiles column."""
    found: list[tuple[str, str]] = []
    query = result.get("query")
    if isinstance(query, dict) and query.get("canonical"):
        found.append(("query (SMARTS)" if query.get("interpreted_as") == "smarts" else "query", query["canonical"]))
    if isinstance(result.get("smiles"), str) and result["smiles"]:
        found.append((query if isinstance(query, str) else "structure", result["smiles"]))
    for key, value in result.items():
        if isinstance(value, dict) and isinstance(value.get("smiles"), str) and value["smiles"]:
            found.append((value.get("name") or key, value["smiles"]))
    if not found:
        return []
    return ["| name | smiles |", "| --- | --- |", *(f"| {_cell(n)} | {_cell(s)} |" for n, s in found), ""]


def _cap(value: Any, max_rows: int | None) -> Any:
    """Shorten a long list of values (e.g. synonyms) to max_rows, noting how many were left out."""
    if max_rows is None or not isinstance(value, list) or len(value) <= max_rows:
        return value
    return [*value[:max_rows], f"… {len(value) - max_rows} more"]


def _rows_to_table(rows: list[dict[str, Any]]) -> list[str]:
    """Rows as a GitHub-flavoured Markdown table."""
    if not rows:
        return ["_(no rows)_", ""]
    cols = list(dict.fromkeys(c for r in rows for c in r))
    out = ["| " + " | ".join(cols) + " |", "| " + " | ".join("---" for _ in cols) + " |"]
    out += ["| " + " | ".join(_cell(r.get(c)) for c in cols) + " |" for r in rows]
    return [*out, ""]


def _cell(v: Any) -> str:
    """One value as Markdown table-cell text."""
    if v is None:
        return ""
    if isinstance(v, float):
        v = f"{v:.6g}"
    elif isinstance(v, list) and not any(isinstance(x, (list, dict)) for x in v):
        v = ", ".join(map(str, v))
    elif isinstance(v, (list, dict)):
        v = json.dumps(v, ensure_ascii=False, default=str)
    return str(v).replace("|", "\\|").replace("\n", " ")
